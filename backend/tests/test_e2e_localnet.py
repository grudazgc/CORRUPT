"""End-to-end flow over HTTP against a live local validator.

Requires:
  * `solana-test-validator` running and the program deployed
  * `python scripts/bootstrap.py` already executed
  * CORRUPT_VERIFIER_KEYPAIR pointing at the keypair written by bootstrap

Run with:
    pytest tests/test_e2e_localnet.py --run-validator-tests
"""

from __future__ import annotations

import base64
import os
import time
from pathlib import Path

import pytest
from fastapi.testclient import TestClient
from solders.keypair import Keypair
from solders.pubkey import Pubkey
from solders.transaction import VersionedTransaction

from app.config import get_settings
from app.solana import SolanaClient, instructions
from app.solana.client import deserialize_config
from app.solana.instructions import associated_token_address

RPC = os.environ.get("CORRUPT_TEST_RPC", "http://127.0.0.1:8899")

pytestmark = [
    pytest.mark.skipif(
        not os.environ.get("CORRUPT_VERIFIER_KEYPAIR")
        or not Path(os.environ["CORRUPT_VERIFIER_KEYPAIR"]).exists(),
        reason="needs CORRUPT_VERIFIER_KEYPAIR written by scripts/bootstrap.py",
    ),
    pytest.mark.skipif(
        "not config.getoption('--run-validator-tests')",
        reason="pass --run-validator-tests to exercise the live local validator",
    ),
]

REPORT = {
    "title": "End-to-end test report",
    "summary": "A synthetic report used by the automated end-to-end test.",
    "description": (
        "This report is generated by the test suite to exercise the full "
        "submit, anchor, verify, and payout path against a local validator."
    ),
    "category": 2,
    "jurisdiction": "PL-MZ",
    "entity_name": "Test Entity",
}


def _auth(client: TestClient, keypair: Keypair) -> str:
    wallet = str(keypair.pubkey())
    challenge = client.post("/api/auth/challenge", json={"wallet": wallet}).json()
    signature = str(keypair.sign_message(challenge["message"].encode()))
    response = client.post(
        "/api/auth/verify", json={"wallet": wallet, "signature": signature}
    )
    assert response.status_code == 200, response.text
    return response.json()["access_token"]


def _fund(keypair: Keypair, lamports: int = 2 * 10**9) -> None:
    with SolanaClient(RPC) as solana:
        solana.request_airdrop(keypair.pubkey(), lamports)
    time.sleep(3)


def _token_balance(owner: Pubkey, mint: Pubkey) -> int:
    with SolanaClient(RPC) as solana:
        account = solana.get_account(associated_token_address(owner, mint))
    if account is None:
        return 0
    # SPL token account layout: mint(32) owner(32) amount(8), so amount starts at 64.
    return int.from_bytes(account.data[64:72], "little")


def _sign(transaction: VersionedTransaction, keypair: Keypair) -> VersionedTransaction:
    """Adds a signature to an unsigned transaction built by the backend."""

    return VersionedTransaction(transaction.message, [keypair])


def test_program_state_is_reachable(client: TestClient) -> None:
    program_id = Pubkey.from_string(get_settings().program_id)
    with SolanaClient(RPC) as solana:
        assert solana._call("getHealth") == "ok"
        account = solana.get_account(instructions.config_pda(program_id)[0])
    assert account is not None, "run scripts/bootstrap.py before this test"
    config = deserialize_config(account.data)
    assert config.min_reward > 0
    assert config.reward_mint != str(Pubkey.default())
    assert config.total_budget >= config.total_distributed


def test_public_config_reflects_chain(client: TestClient) -> None:
    config = client.get("/api/public/config").json()
    program_id = Pubkey.from_string(get_settings().program_id)
    with SolanaClient(RPC) as solana:
        on_chain = deserialize_config(
            solana.get_account(instructions.config_pda(program_id)[0]).data
        )
    assert config["reward_mint"] == on_chain.reward_mint
    assert config["treasury"] == on_chain.treasury
    assert config["total_budget"] == on_chain.total_budget
    assert config["min_reward"] == on_chain.min_reward
    assert config["token_symbol"] == "CORRUPT"


def test_full_report_lifecycle_pays_reward(client: TestClient) -> None:
    program_id = Pubkey.from_string(get_settings().program_id)
    with SolanaClient(RPC) as solana:
        config = deserialize_config(
            solana.get_account(instructions.config_pda(program_id)[0]).data
        )
    mint = Pubkey.from_string(config.reward_mint)

    reporter = Keypair()
    _fund(reporter)
    headers = {"Authorization": f"Bearer {_auth(client, reporter)}"}

    report_id = client.post("/api/reports", json=REPORT, headers=headers).json()["id"]
    assert (
        client.post(
            f"/api/reports/{report_id}/evidence",
            headers=headers,
            files={"file": ("proof.txt", b"evidence body", "text/plain")},
        ).status_code
        == 200
    )

    prepared = client.post(f"/api/reports/{report_id}/prepare", headers=headers)
    assert prepared.status_code == 200, prepared.text
    on_chain_id = prepared.json()["on_chain_id"]

    transaction = VersionedTransaction.from_bytes(
        base64.b64decode(prepared.json()["transaction"])
    )
    # The backend already embedded a fresh blockhash, so the wallet only needs
    # to add its signature.
    signed = _sign(transaction, reporter)

    with SolanaClient(RPC) as solana:
        signature = solana.send_transaction(signed)
        assert solana.confirm_signature(signature), "anchor transaction not confirmed"

    confirmed = client.post(
        f"/api/reports/{report_id}/confirm",
        json={"signature": str(signature)},
        headers=headers,
    )
    assert confirmed.status_code == 200, confirmed.text
    assert confirmed.json()["status"] == "pending"
    assert confirmed.json()["on_chain_id"] == on_chain_id

    before = _token_balance(reporter.pubkey(), mint)
    verified = client.post(
        f"/api/verifier/reports/{report_id}/verify",
        json={"reward_amount": 5_000_000, "note": "verified by e2e test"},
        headers={"X-Verifier-Key": os.environ["CORRUPT_VERIFIER_API_KEY"]},
    )
    assert verified.status_code == 200, verified.text
    assert verified.json()["status"] == "verified"
    assert verified.json()["reward_amount"] == 5_000_000

    time.sleep(2)
    after = _token_balance(reporter.pubkey(), mint)
    assert after - before == 5_000_000, f"expected 5 CORRUPT, went {before} -> {after}"

    detail = client.get(f"/api/reports/{report_id}", headers=headers).json()
    assert detail["status"] == "verified"
    assert detail["reward_amount"] == 5_000_000
    assert any(step["step"] == "verified" for step in detail["timeline"])


def test_rejected_report_pays_nothing(client: TestClient) -> None:
    reporter = Keypair()
    _fund(reporter)
    headers = {"Authorization": f"Bearer {_auth(client, reporter)}"}

    payload = dict(REPORT, title="Rejected end-to-end report", summary="Rejected by test.")
    report_id = client.post("/api/reports", json=payload, headers=headers).json()["id"]
    client.post(
        f"/api/reports/{report_id}/evidence",
        headers=headers,
        files={"file": ("proof.txt", b"weak evidence", "text/plain")},
    )
    prepared = client.post(f"/api/reports/{report_id}/prepare", headers=headers).json()

    transaction = VersionedTransaction.from_bytes(base64.b64decode(prepared["transaction"]))
    signed = _sign(transaction, reporter)
    with SolanaClient(RPC) as solana:
        signature = solana.send_transaction(signed)
        assert solana.confirm_signature(signature)
    client.post(
        f"/api/reports/{report_id}/confirm",
        json={"signature": str(signature)},
        headers=headers,
    )

    rejected = client.post(
        f"/api/verifier/reports/{report_id}/reject",
        json={"note": "insufficient evidence"},
        headers={"X-Verifier-Key": os.environ["CORRUPT_VERIFIER_API_KEY"]},
    )
    assert rejected.status_code == 200, rejected.text
    assert rejected.json()["status"] == "rejected"
    assert rejected.json()["reward_amount"] is None


def test_pause_freezes_submissions(client: TestClient) -> None:
    admin = {"X-Admin-Key": os.environ["CORRUPT_ADMIN_API_KEY"]}
    program_id = Pubkey.from_string(get_settings().program_id)

    paused = client.post("/api/admin/pause", json={"paused": True}, headers=admin)
    assert paused.status_code == 200, paused.text
    assert paused.json()["paused"] is True

    try:
        # The pause is written on-chain, not just in the database.
        with SolanaClient(RPC) as solana:
            on_chain = deserialize_config(
                solana.get_account(instructions.config_pda(program_id)[0]).data
            )
        assert on_chain.paused is True

        reporter = Keypair()
        _fund(reporter)
        headers = {"Authorization": f"Bearer {_auth(client, reporter)}"}
        payload = dict(REPORT, title="Paused report", summary="Submitted while paused.")
        report_id = client.post("/api/reports", json=payload, headers=headers).json()["id"]
        client.post(
            f"/api/reports/{report_id}/evidence",
            headers=headers,
            files={"file": ("proof.txt", b"evidence", "text/plain")},
        )

        # The backend refuses to build an anchor transaction while paused, so
        # the reporter never wastes a fee on a transaction that would fail.
        blocked = client.post(f"/api/reports/{report_id}/prepare", headers=headers)
        assert blocked.status_code == 409, blocked.text
        assert "paused" in blocked.json()["detail"].lower()
    finally:
        resumed = client.post("/api/admin/pause", json={"paused": False}, headers=admin)
        assert resumed.status_code == 200
        assert resumed.json()["paused"] is False

    with SolanaClient(RPC) as solana:
        on_chain = deserialize_config(
            solana.get_account(instructions.config_pda(program_id)[0]).data
        )
    assert on_chain.paused is False
